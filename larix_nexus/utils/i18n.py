# -*- coding: utf-8 -*-
"""Internationalization (i18n) module for Larix Nexus Desktop.

Provides centralized translation management with runtime language switching.
"""

from __future__ import annotations

import os
from typing import Optional, Dict, Any

from PySide6.QtCore import QObject, Signal, Slot, QSettings, QLocale, QLibraryInfo, QTranslator, QCoreApplication
from PySide6.QtWidgets import QApplication

SETTINGS_ORG = "Larix"
SETTINGS_APP = "NexusDesktop"
SETTINGS_LANGUAGE_KEY = "ui/language"
LANGUAGE_RU = "ru"
LANGUAGE_EN = "en"


_TRANSLATIONS: Dict[str, Dict[str, str]] = {
    "ru": {},
    "en": {}
}


def _init_translations():
    global _TRANSLATIONS
    
    _TRANSLATIONS = {
        "ru": {
        },
        "en": {
        }
    }


_init_translations()


class LanguageManager(QObject):
    languageChanged = Signal(str)
    
    _instance: Optional['LanguageManager'] = None
    
    def __init__(self, parent=None):
        super().__init__(parent)
        self._current_language = LANGUAGE_RU
        self._translators: list[QTranslator] = []
        self._app = None
    
    @classmethod
    def instance(cls) -> 'LanguageManager':
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance
    
    @classmethod
    def initialize(cls, app: QApplication) -> 'LanguageManager':
        inst = cls.instance()
        inst._app = app
        saved = inst._load_saved_language()
        inst._current_language = saved
        inst._apply_qt_translators()
        return inst
    
    @property
    def current_language(self) -> str:
        return self._current_language
    
    def is_russian(self) -> bool:
        return self._current_language == LANGUAGE_RU
    
    def is_english(self) -> bool:
        return self._current_language == LANGUAGE_EN
    
    def t(self, key: str, **kwargs) -> str:
        lang_dict = _TRANSLATIONS.get(self._current_language, {})
        text = lang_dict.get(key, key)
        if kwargs:
            try:
                text = text.format(**kwargs)
            except (KeyError, ValueError):
                pass
        return text
    
    def switch_language(self, language: str):
        if language == self._current_language:
            return
        
        old_lang = self._current_language
        self._current_language = language
        self._save_language(language)
        self._apply_qt_translators()
        self.languageChanged.emit(language)
    
    def toggle_language(self):
        new_lang = LANGUAGE_EN if self._current_language == LANGUAGE_RU else LANGUAGE_RU
        self.switch_language(new_lang)
    
    def _load_saved_language(self) -> str:
        try:
            s = QSettings(SETTINGS_ORG, SETTINGS_APP)
            val = s.value(SETTINGS_LANGUAGE_KEY, LANGUAGE_RU)
            return str(val) if val in (LANGUAGE_RU, LANGUAGE_EN) else LANGUAGE_RU
        except Exception:
            return LANGUAGE_RU
    
    def _save_language(self, language: str):
        try:
            s = QSettings(SETTINGS_ORG, SETTINGS_APP)
            s.setValue(SETTINGS_LANGUAGE_KEY, language)
            s.sync()
        except Exception:
            pass
    
    def _apply_qt_translators(self):
        if not self._app:
            return
        
        for tr in self._translators:
            try:
                self._app.removeTranslator(tr)
            except Exception:
                pass
        self._translators.clear()
        
        if self._current_language == LANGUAGE_RU:
            QLocale.setDefault(QLocale(QLocale.Russian, QLocale.Russia))
            tr_path = QLibraryInfo.path(QLibraryInfo.TranslationsPath)
            for name in ("qtbase_ru", "qt_ru"):
                tr = QTranslator(self._app)
                if tr.load(name, tr_path):
                    self._app.installTranslator(tr)
                    self._translators.append(tr)
        else:
            QLocale.setDefault(QLocale(QLocale.English, QLocale.UnitedStates))


_lang_manager: Optional[LanguageManager] = None


def get_language_manager() -> LanguageManager:
    global _lang_manager
    if _lang_manager is None:
        _lang_manager = LanguageManager.instance()
    return _lang_manager


def t(key: str, **kwargs) -> str:
    return get_language_manager().t(key, **kwargs)


def current_language() -> str:
    return get_language_manager().current_language


def is_russian() -> bool:
    return get_language_manager().is_russian()


def is_english() -> bool:
    return get_language_manager().is_english()


def switch_language(language: str):
    get_language_manager().switch_language(language)


def toggle_language():
    get_language_manager().toggle_language()


def initialize_i18n(app: QApplication) -> LanguageManager:
    return LanguageManager.initialize(app)


