def get_status_translation(status: str) -> str:
    """Translate API document status codes for display."""
    if status is None:
        return ""
    raw = str(status).strip()
    if not raw:
        return ""

    status_map = {
        "InDevelopment": "status.in_development",
        "InProgress": "status.in_progress",
        "Approved": "status.approved",
        "Rejected": "status.rejected",
        "Archived": "status.archived",
        "Published": "status.published",
        "Draft": "status.draft",
        "Review": "status.review",
        "Development": "status.in_development",
        "Completed": "status.completed",
        "Pending": "status.pending",
        "Active": "status.active",
        "Deleted": "status.deleted",
        "Processing": "status.processing",
        "Ready": "status.ready",
        "New": "status.new",
    }
    norm = raw.replace(" ", "").replace("_", "").lower()
    aliases = {
        "indevelopment": "status.in_development",
        "development": "status.in_development",
        "inprogress": "status.in_progress",
        "approved": "status.approved",
        "rejected": "status.rejected",
        "archived": "status.archived",
        "published": "status.published",
        "draft": "status.draft",
        "review": "status.review",
        "completed": "status.completed",
        "pending": "status.pending",
        "active": "status.active",
        "deleted": "status.deleted",
        "processing": "status.processing",
        "ready": "status.ready",
        "new": "status.new",
    }
    i18n_key = status_map.get(raw) or aliases.get(norm)
    if i18n_key:
        return t(i18n_key)
    return raw


def get_month_name(month: int) -> str:
    month_keys = [
        "months.january", "months.february", "months.march", "months.april",
        "months.may", "months.june", "months.july", "months.august",
        "months.september", "months.october", "months.november", "months.december"
    ]
    if 1 <= month <= 12:
        return t(month_keys[month - 1])
    return str(month)
